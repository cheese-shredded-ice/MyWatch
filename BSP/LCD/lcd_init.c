/* Debug watch: HAL_OK=0, HAL_ERROR=1, HAL_BUSY=2, HAL_TIMEOUT=3.
 * HAL_OK confirms the STM32 transfer, not reception by the LCD.
 */
volatile HAL_StatusTypeDef lcd_spi_status = HAL_OK;
volatile uint32_t lcd_spi_error = HAL_SPI_ERROR_NONE;

static void LCD_Transmit(const uint8_t *data, uint16_t size)
{
    lcd_spi_status = HAL_SPI_Transmit(&hspi1, data, size, 100U);
    if (lcd_spi_status != HAL_OK)
    {
        lcd_spi_error = HAL_SPI_GetError(&hspi1);
        Error_Handler();
    }
}


/******************************************************************************
      函数说明：LCD端口初始化
      入口数据：无
      返回值：  无
******************************************************************************/
void LCD_GPIO_Init(void)
{
	GPIO_InitTypeDef  GPIO_InitStructure = {0};
	
 	__HAL_RCC_GPIOB_CLK_ENABLE();
	
	GPIO_InitStructure.Pin = RES_PIN|CS_PIN|DC_PIN;	 
 	GPIO_InitStructure.Mode = GPIO_MODE_OUTPUT_PP; 		 //推挽输出
	GPIO_InitStructure.Speed = GPIO_SPEED_FREQ_VERY_HIGH;//速度50MHz
 	HAL_GPIO_Init(GPIOB, &GPIO_InitStructure);	  //初始化GPIOB
 	HAL_GPIO_WritePin(GPIOB, RES_PIN|CS_PIN|DC_PIN, GPIO_PIN_SET);
}

